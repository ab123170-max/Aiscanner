/**
 * Gets a translated string for a given key and language code.
 * Falls back to English if the key is not found.
 */
export function translate(key, lang = 'en', replacements = {}) {
  const dictionary = translations[lang] || translations['en'];
  let text = dictionary[key] || translations['en'][key] || key;

  // Perform replacements if any
  Object.keys(replacements).forEach(rKey => {
    text = text.replace(`{${rKey}}`, replacements[rKey]);
  });

  return text;
}
